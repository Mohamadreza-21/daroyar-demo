export function seededRandom(seed) {
  let value = seed
  return () => {
    value = (value * 1664525 + 1013904223) % 4294967296
    return value / 4294967296
  }
}

export function buildReviews(productId, count, baseRating, rand, now) {
  return Array.from({ length: count }, (_, index) => {
    const [comment, rating] = COMMENTS[Math.floor(rand() * COMMENTS.length)]
    return {
      productId,
      reviewerName: NAMES[Math.floor(rand() * NAMES.length)],
      rating: Math.max(1, Math.min(5, Math.round(rating * 0.6 + baseRating * 0.4))),
      comment,
      date: new Date(now - (index + 1) * 9 * 86400000 - Math.floor(rand() * 5) * 86400000).toISOString(),
    }
  })
}
